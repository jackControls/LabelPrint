    /// "E11" for "T0224C…"; nil when the prefix is not known.
    public static func name(forBluetoothName bt: String) -> String? {
        let upper = bt.uppercased()
        for length in [6, 5] where upper.count >= length {
            if let hit = prefixes[String(upper.prefix(length))] { return hit }
        }
        return nil
    }
